export function t(key) {
  const e = D[key];
  if (!e) return key;
  return (lang === 'sw' ? e[1] : e[0]) || e[0];
}
// Server-written tracking titles → Kiswahili
const EV = [
  [/^Booking created$/, 'Booking imeundwa'], [/^Awaiting deposit$/, 'Inasubiri amana'],
  [/^Booking confirmed$/, 'Booking imethibitishwa'], [/^Deposit received — deliver cargo to the warehouse$/, 'Amana imepokelewa — leta mzigo ghalani'],
  [/^Cargo received at warehouse$/, 'Mzigo umepokelewa ghalani'], [/^Loaded for shipment$/, 'Umepakiwa kwa safari'],
  [/^Removed from container$/, 'Umeondolewa kwenye kontena'], [/^Departed (\w+)$/, 'Umeondoka $1'], [/^Arrived at (\w+)$/, 'Umefika $1'],
  [/^Customs clearance in progress$/, 'Unashughulikiwa forodhani'], [/^Ready for collection$/, 'Tayari kuchukuliwa'],
  [/^Cargo collected$/, 'Mzigo umechukuliwa'], [/^Released to (.+)$/, 'Umekabidhiwa kwa $1'], [/^Booking cancelled$/, 'Booking imeghairiwa'],
  [/^Container (.+)$/, 'Kontena $1'],
];
export function tr(text) {
  if (lang !== 'sw' || !text) return text;
  for (const [re, sw] of EV) if (re.test(text)) return text.replace(re, sw);
  return text;
}
export function getLang() { return lang; }
export function setLang(l) {
  lang = l;
  try { localStorage.setItem('hc.lang', l); } catch { /* ignore */ }
  document.documentElement.lang = l;
}
export function hasKey(k) { return !!D[k]; }
document.documentElement.lang = lang;
